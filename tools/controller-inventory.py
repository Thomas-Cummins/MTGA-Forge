#!/usr/bin/env python3
"""Inventory inherited AI hooks without building Forge or generating Arena schemas."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
from collections import Counter

ROOT = Path(__file__).resolve().parents[1]
HERE = ROOT / 'tools/controller-inventory'
SOURCES = [
    'forge/forge-ai/src/main/java/forge/ai/PlayerControllerAi.java',
    'forge/forge-game/src/main/java/forge/game/player/PlayerController.java',
    'forge/forge-gui-mtga/src/main/java/forge/mtga/forge/ForgeBackend.java',
    'forge/forge-ai/src/main/java/forge/ai/AiCostDecision.java',
]
HUMAN = 'ForgeBackend.MtgaController'
COST_HUMAN = 'ForgeBackend.MtgaCostDecision'


def digest(text):
    return hashlib.sha256(text.encode()).hexdigest()


def extract(java, paths):
    result = subprocess.run([java, str(HERE / 'ControllerInventory.java'), *map(str, paths)],
                            check=True, text=True, capture_output=True)
    return json.loads(result.stdout)


def method_map(rows, cls):
    result = {m['key']: m for m in rows if m['class'] == cls}
    if len(result) != sum(m['class'] == cls for m in rows):
        raise ValueError(f'Ambiguous normalized signatures in {cls}; use resolved types before continuing')
    return result


def fingerprint(method, override):
    return digest(method['source'] + '\n' + (override['source'] if override else ''))


def reviewed_status(method, override, reviews):
    scope = 'cost' if method['class'] == 'AiCostDecision' else 'controller'
    review = reviews.get(scope + ':' + method['key'])
    if review:
        if review['fingerprint'] != fingerprint(method, override):
            return 'Review stale', review['note'] + ' Source changed since this classification; recheck it.'
        return review['status'], review['note']
    if override:
        return 'Implemented hook', 'Has an Arena override; this is coverage, not proof of correct behavior in every branch.'
    return 'Needs path review', 'Inherited implementation; trace reachability and whether an actual player choice exists.'


def link(method):
    path = Path(method['file']).resolve().relative_to(ROOT)
    return f'[{method["class"].split(".")[-1]}:{method["line"]}](../{path.as_posix()}#L{method["line"]})'


def safe(text):
    return text.replace('|', '\\|').replace('\n', ' ')


def render(rows, reviews):
    ai, human = method_map(rows, 'PlayerControllerAi'), method_map(rows, HUMAN)
    costs, human_costs = method_map(rows, 'AiCostDecision'), method_map(rows, COST_HUMAN)
    base = method_map(rows, 'PlayerController')
    statuses = Counter(reviewed_status(m, human.get(k), reviews)[0] for k, m in ai.items())
    lines = ['# Human controller method inventory', '',
        'Generated by `python3 tools/controller-inventory.py`. Requires a JDK 17 or newer; '
        'no Forge dependencies, protocol schemas, client database, or network access.', '',
        f'PlayerControllerAi declares **{len(ai)}** public/protected instance methods: '
        f'**{sum(k in human for k in ai)}** have exact-signature Arena overrides and '
        f'**{sum(k not in human for k in ai)}** remain inherited. '
        'Constructors, static methods, and inaccessible internal helpers are excluded.', '',
        'This is an inventory of source hooks, not a count of bugs. '
        '**Choice gap** means source shows a user decision still made automatically if that path is reached; '
        'a rig is needed to prove reachability and behavior for each card. '
        '**Partial override** means only some cases reach Arena. '
        '**Mode-specific choice** means a decision exists in a mechanic or mode that needs a separate support assessment. '
        '**Delegates to Arena** and **Alternate route** explain why a missing override is not automatically a bug. '
        '**Needs path review** is deliberately unresolved. '
        '**Implemented hook** does not mean runtime verified.', '',
        'Classification notes are manually reviewed in `tools/controller-inventory/review.json`. '
        'Each note is tied to a hash of the method and its override; edits mark it **Review stale**. '
        'Every newly added method appears automatically. Signature comparison uses Java syntax trees, '
        'normalizes qualified type spellings, and preserves parameter types, generics, arrays, and overloads. '
        'It does not perform Java type resolution or prove a complete runtime call graph.', '',
        'Run `python3 tools/controller-inventory.py --check` to detect report drift. '
        'Use `--java <path-to-java>` to select a JDK and `--json` for the full extracted methods and source. '
        'Run parser/classification regression checks with `python3 tools/controller-inventory/test_inventory.py`.', '',
        '## Classification counts', '', '| Classification | Methods |', '|---|---:|']
    lines += [f'| {status} | {count} |' for status, count in sorted(statuses.items())]
    lines += ['', '## PlayerControllerAi hooks', '',
              '| Signature | Arena override | Classification | Reason / next check | Source |',
              '|---|---|---|---|---|']
    priority = ['Choice gap', 'Partial override', 'Mode-specific choice', 'Needs path review',
                'Review stale', 'Delegates to Arena', 'Alternate route', 'Implemented hook', 'Infrastructure']
    def ordering(pair):
        key, method = pair
        status = reviewed_status(method, human.get(key), reviews)[0]
        return (priority.index(status), key)
    for key, method in sorted(ai.items(), key=ordering):
        override = human.get(key)
        status, note = reviewed_status(method, override, reviews)
        if override and override['super_calls']:
            note += ' Calls superclass: ' + ', '.join(override['super_calls']) + '.'
        lines.append(f'| `{key}` | {"Yes" if override else "No"} | {status} | {safe(note)} | '
                     + link(method) + ('; ' + link(override) if override else '') + ' |')
    lines += ['', '## Contextual hooks supplied by PlayerController', '',
              'These Arena overrides are absent from PlayerControllerAi itself and would be missed by comparing only the two subclasses.', '',
              '| Signature | Classification | Source |', '|---|---|---|']
    for key, method in human.items():
        if key not in ai:
            if key not in base:
                raise ValueError('Arena override not found in either superclass: ' + key)
            lines.append(f'| `{key}` | Implemented hook | {link(base[key])}; {link(method)} |')
    lines += ['', '## Cost decision hooks', '',
              'MtgaCostDecision extends AiCostDecision. This second inheritance surface can silently select payment objects '
              'even when the controller itself has an override. Fixed numeric costs are intentionally automatic. '
              'The table includes public/protected helpers as well as visitor methods.', '',
              '| Signature | Arena override | Classification | Reason / next check | Source |',
              '|---|---|---|---|---|']
    for key, method in costs.items():
        override = human_costs.get(key)
        status, note = reviewed_status(method, override, reviews)
        lines.append(f'| `{key}` | {"Yes" if override else "No"} | {status} | {safe(note)} | '
                     + link(method) + ('; ' + link(override) if override else '') + ' |')
    lines += ['', '## Limits and follow-up', '',
        '- The AI class has internal helpers that cannot be overridden from the Arena package. '
        'For example, copied-spell retargeting is handled inside inherited stack-play code; see the partial stack-play override.',
        '- The normal casting path bypasses some inherited hooks. Conversely, an override can still call AI code directly. '
        'Inspect the listed superclass calls and the manually noted alternate paths.',
        '- The concrete defaults and final forwarding helpers on PlayerController are not counted as AI hooks. '
        'Their source is included in JSON output for further call-path analysis.',
        '- Runtime tracing should record the decision hook, source card, seat, phase, and options, '
        'then reproduce a choice different from the AI preference in SelfPlay. Do not dump hidden opponent information.',
        '- The inventory does not cover missing actions or state translation, such as the Fellwar Stone bug. '
        'It also does not establish that the client can display every listed mechanic.', '', '## Source fingerprints', '']
    lines += [f'- `{path}`: `{digest((ROOT/path).read_text())}`' for path in SOURCES]
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--java', default='java')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--json', action='store_true')
    args = parser.parse_args()
    rows = extract(args.java, [ROOT / p for p in SOURCES])
    if args.json:
        # Keep the output portable; never include machine-specific absolute paths.
        for method in rows:
            method['file'] = str(Path(method['file']).relative_to(ROOT))
        print(json.dumps(rows, indent=2))
        return 0
    reviews = json.loads((HERE / 'review.json').read_text())
    report = render(rows, reviews)
    output = ROOT / 'docs/controller-inventory.md'
    if args.check:
        if not output.exists() or output.read_text() != report:
            print('Controller inventory is stale; regenerate with python3 tools/controller-inventory.py', file=sys.stderr)
            return 1
        print('Controller inventory is current.')
    else:
        output.write_text(report)
        print(f'Wrote {output.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
